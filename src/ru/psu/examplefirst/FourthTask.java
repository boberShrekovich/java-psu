    private void menuSaveAsTextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuSaveAsTextActionPerformed
        // TODO add your handling code here:
        JFileChooser fc = new JFileChooser();
        
        FileNameExtensionFilter filter = new FileNameExtensionFilter("Text file", "txt");
        fc.setFileFilter(filter);
        
        int result = fc.showSaveDialog(this);
        
        if (result == JFileChooser.APPROVE_OPTION){
            File file = fc.getSelectedFile();
            
            String path = file.getAbsolutePath();
            if (!path.endsWith(".txt"))
                file = new File(path + ".txt");
            
            try (FileWriter fw = new FileWriter(file);
                BufferedWriter bw = new BufferedWriter(fw)){
                
                
                for (int i = 0; i < jTable.getRowCount(); i++){
                    if (jTable.getValueAt(i, 3) == null)
                        throw new InvalidValueException("The result field must be filled in!!!");
                    
                    for (int j = 0; j < jTable.getColumnCount(); j++){
                        bw.write(jTable.getValueAt(i, j).toString() + " ");
                    }
                    bw.newLine();
                }
                
            } catch (InvalidValueException e) {
                if (file.exists())
                    file.delete();
                JOptionPane.showMessageDialog(null, e.getMessage(), "ERROR!!!", JOptionPane.ERROR_MESSAGE);
            } catch (IOException ex) {
                Logger.getLogger(FourthTask.class.getName()).log(Level.SEVERE, null, ex);
            }  
            
        }
    }//GEN-LAST:event_menuSaveAsTextActionPerformed

    private void menuLoadTextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuLoadTextActionPerformed
        // TODO add your handling code here:
        JFileChooser fc = new JFileChooser();
        
        FileNameExtensionFilter filter = new FileNameExtensionFilter("Text file", "txt");
        fc.setFileFilter(filter);
        
        int result = fc.showOpenDialog(this);
        
        if (result == JFileChooser.APPROVE_OPTION){
            File file = fc.getSelectedFile();
            
            String path = file.getAbsolutePath();
            if (!path.endsWith(".txt"))
                file = new File(path + ".txt");
            
            try {
                FileReader fr = new FileReader(file);
                BufferedReader br = new BufferedReader(fr);
                
                DefaultTableModel model = (DefaultTableModel)jTable.getModel();
                if (model.getRowCount() != 0)
                    throw new InvalidValueException("You cannot fill a table while it contains value!!!");
                if (!isClear)
                    throw new InvalidValueException("You cannot fill a table while it is cleared!!!");
                
                Object[] lines = br.lines().toArray();
                
                for (int i = 0; i < lines.length; i++){
                    String[] row = lines[i].toString().split(" ");
                    model.addRow(row);
                }
                
                br.close();
                fr.close();
                
            } catch (FileNotFoundException ex) {
                JOptionPane.showMessageDialog(null, "File not found!!!", "ERROR!!!", JOptionPane.ERROR_MESSAGE);
                Logger.getLogger(FourthTask.class.getName()).log(Level.SEVERE, null, ex);
            } catch (IOException ex) {
                Logger.getLogger(FourthTask.class.getName()).log(Level.SEVERE, null, ex);
            } catch (InvalidValueException ex) {
                JOptionPane.showMessageDialog(null, ex.getMessage(), "ERROR!!!", JOptionPane.ERROR_MESSAGE);
            } 
        }
    }//GEN-LAST:event_menuLoadTextActionPerformed

