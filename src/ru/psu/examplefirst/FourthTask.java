    private void menuLoadBinaryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuLoadBinaryActionPerformed
        // TODO add your handling code here:
        JFileChooser fc = new JFileChooser();
        
        FileNameExtensionFilter filter = new FileNameExtensionFilter("Binary file", "bin");
        fc.setFileFilter(filter);
        
        int result = fc.showOpenDialog(this);
        
        if (result == JFileChooser.APPROVE_OPTION){
            File file = fc.getSelectedFile();
            
            String path = file.getAbsolutePath();
            if (!path.endsWith(".bin"))
                file = new File(path + ".bin");
            
            try {
                FileInputStream fis = new FileInputStream(file);
                ObjectInputStream ois = new ObjectInputStream(fis);
                
                DefaultTableModel model = (DefaultTableModel)jTable.getModel();
                if (model.getRowCount() != 0)
                    throw new InvalidValueException("You cannot fill a table while it contains value!!!");
                if (!isClear)
                    throw new InvalidValueException("You cannot fill a table while it is cleared!!!");
                
                while (fis.available() > 0) {
                    RecIntegral integral = (RecIntegral) ois.readObject();
                    
                    model.addRow(new Object[]{
                        integral.getBotLimit(),
                        integral.getTopLimit(),
                        integral.getStep(),
                        integral.getResult()
                    });
                }
                
            } catch (FileNotFoundException ex) {
                Logger.getLogger(FourthTask.class.getName()).log(Level.SEVERE, null, ex);
            } catch (ClassNotFoundException | IOException ex) {
                Logger.getLogger(FourthTask.class.getName()).log(Level.SEVERE, null, ex);
            } catch (InvalidValueException ex) {
                JOptionPane.showMessageDialog(null, ex.getMessage(), "ERROR!!!", JOptionPane.ERROR_MESSAGE);
            } 
            
        }
    }//GEN-LAST:event_menuLoadBinaryActionPerformed

    private void menuSaveJSONActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuSaveJSONActionPerformed
        // TODO add your handling code here:
        JFileChooser fc = new JFileChooser();
        
        FileNameExtensionFilter filter = new FileNameExtensionFilter("JSON file", "json");
        fc.setFileFilter(filter);
        
        int result = fc.showSaveDialog(this);
        
        if (result == JFileChooser.APPROVE_OPTION){
            File file = fc.getSelectedFile();
            
            String path = file.getAbsolutePath();
            if (!path.endsWith(".json"))
                file = new File(path + ".json");
            
            try {
                //StringWriter sw = new StringWriter();
                ObjectMapper mapper = new ObjectMapper();
                mapper.enable(com.fasterxml.jackson.databind.SerializationFeature.INDENT_OUTPUT);
                
                List<RecIntegral> list = new ArrayList();
                
                for (int i = 0; i < jTable.getRowCount(); i++){
                    if (jTable.getValueAt(i, 3) == null)
                        throw new InvalidValueException("The result field must be filled in!!!");
                    
                    RecIntegral integral = new RecIntegral(
                                Double.parseDouble(jTable.getValueAt(i, 0).toString()),
                                Double.parseDouble(jTable.getValueAt(i, 1).toString()),
                                Double.parseDouble(jTable.getValueAt(i, 2).toString()),
                                Double.parseDouble(jTable.getValueAt(i, 3).toString())
                    );
                    list.add(integral);
                }
                
                mapper.writeValue(file, list);
                
            } catch (FileNotFoundException ex) {
                Logger.getLogger(FourthTask.class.getName()).log(Level.SEVERE, null, ex);
            } catch (InvalidValueException e){
                if (file.exists())
                    file.delete();
                JOptionPane.showMessageDialog(null, e.getMessage(), "ERROR!!!", JOptionPane.ERROR_MESSAGE);
            } catch (IOException ex) {
                Logger.getLogger(FourthTask.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_menuSaveJSONActionPerformed

